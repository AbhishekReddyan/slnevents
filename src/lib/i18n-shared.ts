export type Dict = typeof en;
// All screen text is English. The English / ಕನ್ನಡ switch changes only the ITEM NAMES
// (and decoration names). To get Kannada screen text back, replace the second `en` with `kn`.
export const dictionaries: Record<Lang, Dict> = { en, kn: en };
export const kannadaScreenText = kn;

/** Fills {placeholders} in a string. */
export const fill = (s: string, vars: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));

export const statusText = (d: Dict, status: OrderStatus) => d[`s_${status}` as keyof Dict];

/** Item name in the chosen language (falls back to English when no Kannada name is set). */
export const itemName = (lang: Lang, i: { name?: string | null; name_kn?: string | null } | null | undefined) =>
  (lang === "kn" && i?.name_kn ? i.name_kn : i?.name) ?? "";

/** Screen text stays English, so database messages are shown as they are. */
export function workerError(_lang: Lang, msg: string): string {
  return msg;
}
